/**
 * Generates typed ABIs for the ORVEX contracts from Foundry artifacts.
 * Usage: bun run abi:gen   (run `bun run contracts:build` first)
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

const NAMES = ['OrvexIdentity', 'OrvexProof', 'OrvexChallenges', 'OrvexLaunchpad', 'OrvexIdeas'] as const
const root = fileURLToPath(new URL('..', import.meta.url))

let out = `// AUTO-GENERATED by scripts/gen-abi.ts from contracts/out. Do not edit by hand.\n`
for (const name of NAMES) {
  const artifact = JSON.parse(readFileSync(join(root, 'contracts/out', `${name}.sol`, `${name}.json`), 'utf8')) as { abi: unknown }
  const exportName = `${name.charAt(0).toLowerCase()}${name.slice(1)}Abi`
  out += `\nexport const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const\n`
}

mkdirSync(join(root, 'src/abi'), { recursive: true })
writeFileSync(join(root, 'src/abi/generated.ts'), out)
console.log(`Wrote src/abi/generated.ts (${NAMES.length} ABIs)`)
